import MagicString from 'magic-string'
import { createHash, randomUUID } from 'node:crypto'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve, sep } from 'node:path'
import type { Plugin } from 'vite'

export interface SubmodelCatalogOptions {
  readonly directory: string
  readonly catalog: string
  readonly factoryModule?: string
  readonly factoryExport?: string
  readonly implementationFile?: string
  readonly implementationExport?: string
  readonly contractSuffix?: string
}

const importPath = (from: string, to: string) => {
  const path = relative(dirname(from), to).split(sep).join('/')
  return path.startsWith('.') ? path : `./${path}`
}

const sourceImportPath = (from: string, to: string) =>
  importPath(from, to).replace(/\.([cm]?)tsx?$/, '.$1js')

/** Generate typed literal imports from explicit contracts, without evaluating application code. */
export const generateSubmodelCatalog = (options: SubmodelCatalogOptions) => {
  const directory = resolve(options.directory)
  const catalog = resolve(options.catalog)
  const suffix = options.contractSuffix ?? '.contract.ts'
  const contracts: string[] = []
  const scan = (path: string) => {
    for (const entry of readdirSync(path, { withFileTypes: true })) {
      if (entry.name.startsWith('.') || entry.name === 'node_modules') {
        continue
      }
      const child = join(path, entry.name)
      if (entry.isDirectory()) {
        scan(child)
      } else if (entry.isFile() && entry.name.endsWith(suffix)) {
        contracts.push(child)
      }
    }
  }
  scan(directory)
  contracts.sort()
  const implementationFiles = contracts.map(file =>
    join(dirname(file), options.implementationFile ?? 'implementation.ts'),
  )
  for (let index = 0; index < contracts.length; index += 1) {
    if (!existsSync(implementationFiles[index]!)) {
      throw new Error(
        `${contracts[index]}: missing Submodel implementation ${implementationFiles[index]}`,
      )
    }
  }
  const factoryExport = options.factoryExport ?? 'lazy'
  const implementationExport = options.implementationExport ?? 'implementation'
  for (const name of [factoryExport, implementationExport]) {
    if (!/^[A-Za-z_$][\w$]*$/.test(name)) {
      throw new Error(`Invalid Submodel export name: ${name}`)
    }
  }
  const imports = contracts.map(
    (file, index) =>
      `import { contract as contract${index} } from ${JSON.stringify(sourceImportPath(catalog, file))}`,
  )
  const code = [
    '// Generated by @foldkit/vite-plugin. Edit contracts and regenerate this file.',
    `import { ${factoryExport} as createHost } from ${JSON.stringify(options.factoryModule ?? 'foldkit/submodel')}`,
    ...imports,
    '',
    `export const contracts = [${contracts.map((_, index) => `contract${index}`).join(', ')}]`,
    '',
    'export const createCatalog = (options: { readonly buildId: string }) => [',
    ...implementationFiles.map(
      (file, index) =>
        `  createHost(contract${index}, { ...options, load: () => import(${JSON.stringify(sourceImportPath(catalog, file))}).then(module => module.${implementationExport}) }),`,
    ),
    ']',
    '',
  ].join('\n')
  return { code, contractFiles: contracts, implementationFiles }
}

/**
 * Validates generated catalogs and the actual emitted startup graph. Catalog
 * generation is explicit so builds cannot silently edit tracked source files.
 */
export const foldkitSubmodels = (options: SubmodelCatalogOptions): Plugin => {
  const generated = generateSubmodelCatalog(options)
  const virtualId = 'virtual:foldkit-submodels/build-id'
  const resolvedVirtualId = `\0${virtualId}`
  const placeholder = '__FOLDKIT_SUBMODELS_BUILD_ID__'
  let isDevelopment = false
  let developmentId = randomUUID()
  let productionId: string | undefined
  const sources = new Map<string, string>()
  return {
    name: 'foldkit-submodels',
    configResolved(config) {
      isDevelopment = config.command === 'serve'
    },
    resolveId(id) {
      return id === virtualId ? resolvedVirtualId : null
    },
    load(id) {
      return id === resolvedVirtualId
        ? `export default ${JSON.stringify(isDevelopment ? developmentId : placeholder)}`
        : null
    },
    transform(code, id) {
      sources.set(id, code)
      return null
    },
    buildStart() {
      productionId = undefined
      for (const file of [
        ...generated.contractFiles,
        ...generated.implementationFiles,
      ]) {
        this.addWatchFile(file)
      }
      if (
        !existsSync(options.catalog) ||
        readFileSync(options.catalog, 'utf8') !== generated.code
      ) {
        this.error(
          `${options.catalog}: Submodel catalog is stale. Run the project's catalog generation command before building.`,
        )
      }
    },
    renderChunk(code) {
      if (!code.includes(placeholder)) {
        return null
      }
      if (productionId === undefined) {
        const hash = createHash('sha256')
        for (const id of [...this.getModuleIds()].sort()) {
          hash.update(id)
          hash.update(this.getModuleInfo(id)?.code ?? sources.get(id) ?? '')
        }
        productionId = hash.digest('hex')
      }
      const output = new MagicString(code)
      let offset = code.indexOf(placeholder)
      while (offset !== -1) {
        output.overwrite(offset, offset + placeholder.length, productionId)
        offset = code.indexOf(placeholder, offset + placeholder.length)
      }
      return {
        code: output.toString(),
        map: output.generateMap({ hires: true }),
      }
    },
    generateBundle(_options, bundle) {
      const chunks = Object.values(bundle).filter(item => item.type === 'chunk')
      const byFile = new Map(chunks.map(chunk => [chunk.fileName, chunk]))
      const initial = new Set<string>()
      const visit = (file: string) => {
        if (initial.has(file)) {
          return
        }
        initial.add(file)
        for (const dependency of byFile.get(file)?.imports ?? []) {
          visit(dependency)
        }
      }
      for (const chunk of chunks) {
        if (chunk.isEntry) {
          visit(chunk.fileName)
        }
      }
      const owners = [...generated.implementationFiles].sort(
        (left, right) => dirname(right).length - dirname(left).length,
      )
      const classify = (id: string) =>
        owners.find(
          file =>
            id === file ||
            (id.startsWith(`${dirname(file)}${sep}`) &&
              /\/(?:index|implementation|view|update|subscriptions?|commands?)(?:[-.][^/]*)?\.[cm]?[jt]sx?$/.test(
                id,
              )),
        )
      const ownerCache = new Map<string, string | undefined>()
      const executable = (id: string) => {
        if (!ownerCache.has(id)) {
          ownerCache.set(id, classify(id))
        }
        return ownerCache.get(id)
      }
      const pathTo = (start: string, matches: (id: string) => boolean) => {
        const queue = [[start]]
        const seen = new Set<string>()
        for (const path of queue) {
          const id = path[path.length - 1]!
          if (seen.has(id)) {
            continue
          }
          seen.add(id)
          if (id !== start && matches(id)) {
            return path
          }
          for (const dependency of this.getModuleInfo(id)?.importedIds ?? []) {
            queue.push([...path, dependency])
          }
        }
        return undefined
      }
      const diagnostics: string[] = []
      for (const contract of generated.contractFiles) {
        const path = pathTo(contract, id => executable(id) !== undefined)
        if (path) {
          diagnostics.push(
            `Submodel contract imports executable code: ${path.join(' -> ')}. Move shared schemas into a contract-only module.`,
          )
        }
      }
      for (const implementation of generated.implementationFiles) {
        const crossing = pathTo(implementation, id => {
          const owner = executable(id)
          return owner !== undefined && owner !== implementation
        })
        if (crossing) {
          diagnostics.push(
            `Cross-route Submodel import: ${crossing.join(' -> ')}. Move shared code outside the route implementations.`,
          )
        }
        for (const chunk of chunks) {
          const leaked = Object.entries(chunk.modules).find(
            ([id, info]) =>
              executable(id) === implementation && info.renderedLength,
          )
          if (initial.has(chunk.fileName) && leaked) {
            diagnostics.push(
              `${leaked[0]}: Submodel implementation is in startup chunk ${chunk.fileName}. Remove the eager import path to this implementation.`,
            )
          }
        }
      }
      if (diagnostics.length > 0) {
        this.error(diagnostics.join('\n\n'))
      }
      this.emitFile({
        type: 'asset',
        fileName: 'foldkit-submodels.json',
        source: JSON.stringify(
          {
            modules: generated.contractFiles.map((file, index) => ({
              contract: importPath(resolve(options.catalog), file),
              implementation: importPath(
                resolve(options.catalog),
                generated.implementationFiles[index]!,
              ),
              chunks: chunks
                .filter(chunk =>
                  Object.hasOwn(
                    chunk.modules,
                    generated.implementationFiles[index]!,
                  ),
                )
                .map(chunk => chunk.fileName),
            })),
          },
          null,
          2,
        ),
      })
    },
    hotUpdate(context) {
      const dependsOnChanged = (start: string) => {
        const root = this.environment.moduleGraph.getModuleById(start)
        const queue = root ? [root] : []
        const seen = new Set(queue)
        for (const node of queue) {
          if (node.file === context.file) {
            return true
          }
          for (const imported of node.importedModules) {
            if (!seen.has(imported)) {
              seen.add(imported)
              queue.push(imported)
            }
          }
        }
        return false
      }
      if (
        context.file.startsWith(`${resolve(options.directory)}${sep}`) ||
        generated.implementationFiles.some(dependsOnChanged)
      ) {
        developmentId = randomUUID()
        const identityModule =
          this.environment.moduleGraph.getModuleById(resolvedVirtualId)
        if (identityModule) {
          this.environment.moduleGraph.invalidateModule(identityModule)
        }
        this.environment.hot.send({ type: 'full-reload' })
        return []
      }
      return undefined
    },
  }
}

/** Write a catalog from an explicit project generation command. */
export const writeSubmodelCatalog = (options: SubmodelCatalogOptions) => {
  const generated = generateSubmodelCatalog(options)
  writeFileSync(options.catalog, generated.code)
  return generated
}
